CREATE OR REPLACE FUNCTION public.update_delivered_orders()
RETURNS void AS $$
BEGIN
  UPDATE public.orders
  SET status = 'delivered'
  WHERE status = 'shipped'
  AND delivery_deadline < now();
END;
$$ LANGUAGE plpgsql;



