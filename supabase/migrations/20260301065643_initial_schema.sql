CREATE OR REPLACE FUNCTION public.update_product_search_vector()
RETURNS TRIGGER AS $$
BEGIN
  NEW.search_vector :=
    to_tsvector('english', COALESCE(NEW.name, '') || ' ' || COALESCE(NEW.description, '') || ' ' || COALESCE(NEW.shop_name, ''));
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_products_update_search_vector
BEFORE INSERT OR UPDATE OF name, description, shop_name
ON public.products
FOR EACH ROW
EXECUTE FUNCTION public.update_product_search_vector();



CREATE OR REPLACE FUNCTION public.recalculate_product_rating_avg()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    UPDATE public.products
    SET rating_avg = COALESCE((SELECT AVG(rating) FROM public.ratings WHERE product_id = OLD.product_id), 0)
    WHERE id = OLD.product_id;
    RETURN OLD;
  ELSE
    UPDATE public.products
    SET rating_avg = COALESCE((SELECT AVG(rating) FROM public.ratings WHERE product_id = NEW.product_id), 0)
    WHERE id = NEW.product_id;
    RETURN NEW;
  END IF;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_ratings_recalculate_avg
AFTER INSERT OR UPDATE OR DELETE ON public.ratings
FOR EACH ROW
EXECUTE FUNCTION public.recalculate_product_rating_avg();



CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Apply to tables with updated_at column
DO $$
DECLARE
  t text;
BEGIN
  FOR t IN 
    SELECT table_name 
    FROM information_schema.columns 
    WHERE column_name = 'updated_at' 
    AND table_schema = 'public'
    AND table_name NOT LIKE 'pg_%'
  LOOP
    EXECUTE format('CREATE TRIGGER tr_%I_set_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', t, t);
  END LOOP;
END;
$$;



-- Users: only user can read/update own row
CREATE POLICY "Users can view own data" ON public.users FOR SELECT USING (auth.uid() = auth_id);
CREATE POLICY "Users can update own data" ON public.users FOR UPDATE USING (auth.uid() = auth_id);

-- Shops: anyone can read, only owner (linked via users.id) can update/delete
-- Since shops references users.id, we need to check users.auth_id
CREATE POLICY "Anyone can view shops" ON public.shops FOR SELECT USING (true);
CREATE POLICY "Owners can manage shops" ON public.shops 
FOR ALL USING (EXISTS (SELECT 1 FROM public.users WHERE id = public.shops.user_id AND auth.uid() = auth_id));

-- Products: anyone can read, only shop owner can manage
CREATE POLICY "Anyone can view products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Shop owners can manage products" ON public.products
FOR ALL USING (EXISTS (
  SELECT 1 FROM public.shops s
  JOIN public.users u ON s.user_id = u.id
  WHERE s.id = public.products.shop_id AND u.auth_id = auth.uid()
));

-- Product Images: anyone can read, only shop owner can manage
