CREATE OR REPLACE FUNCTION public.recalculate_user_affinity(p_user_id int8)
RETURNS void AS $$
DECLARE
    rec RECORD;
BEGIN
    -- Reset current affinities or handle incremental
    -- For simplicity, let's recalculate based on log weights
    -- View = 1, Search = 1.5, Cart Add = 3, Purchase = 10
    
    -- Update Categories
    FOR rec IN 
        SELECT category, SUM(CASE 
            WHEN activity_type = 'view' THEN 1
            WHEN activity_type = 'search' THEN 1.5
            WHEN activity_type = 'cart_add' THEN 3
            WHEN activity_type = 'purchase' THEN 10
            ELSE 0 END) as score
        FROM public.user_activity_log
        WHERE user_id = p_user_id AND category IS NOT NULL
        GROUP BY category
    LOOP
        INSERT INTO public.user_category_affinity (user_id, category, score)
        VALUES (p_user_id, rec.category, rec.score)
        ON CONFLICT (user_id, category) DO UPDATE SET score = rec.score, updated_at = now();
    END LOOP;

    -- Update Tags (Tags is jsonb array of strings)
    FOR rec IN 
        SELECT tag, SUM(CASE 
            WHEN activity_type = 'view' THEN 1
            WHEN activity_type = 'search' THEN 1.5
            WHEN activity_type = 'cart_add' THEN 3
            WHEN activity_type = 'purchase' THEN 10
            ELSE 0 END) as score
        FROM (
            SELECT jsonb_array_elements_text(tags) as tag, activity_type
            FROM public.user_activity_log
            WHERE user_id = p_user_id AND tags IS NOT NULL
        ) t
        GROUP BY tag
    LOOP
        INSERT INTO public.user_tag_affinity (user_id, tag, score)
        VALUES (p_user_id, rec.tag, rec.score)
        ON CONFLICT (user_id, tag) DO UPDATE SET score = rec.score, updated_at = now();
    END LOOP;
END;
$$ LANGUAGE plpgsql;



CREATE OR REPLACE FUNCTION public.refresh_user_recommendations(p_user_id int8)
RETURNS void AS $$
BEGIN
    -- Delete existing recommendations
    DELETE FROM public.user_recommendations WHERE user_id = p_user_id;

    -- Generate new recommendations using a weighted approach
    -- 1. Category Affinity (top 10 based on user preferences)
    INSERT INTO public.user_recommendations (user_id, product_id, score, reason, expires_at)
    SELECT p_user_id, p.id, 0.7 * ca.score, 'Category Affinity: ' || p.category, now() + interval '24 hours'
    FROM public.products p
    JOIN public.user_category_affinity ca ON p.category = ca.category
    WHERE ca.user_id = p_user_id AND p.deleted_at IS NULL
    ORDER BY ca.score DESC, RANDOM()
    LIMIT 10
    ON CONFLICT DO NOTHING;

    -- 2. Tag Affinity (top 5 based on user preferences)
    INSERT INTO public.user_recommendations (user_id, product_id, score, reason, expires_at)
    SELECT p_user_id, p.id, 0.9 * ta.score, 'Based on tags you like: ' || ta.tag, now() + interval '24 hours'
    FROM public.products p
    JOIN public.user_tag_affinity ta ON p.tags ? ta.tag
    WHERE ta.user_id = p_user_id AND p.deleted_at IS NULL
    ORDER BY ta.score DESC, RANDOM()
    LIMIT 5
    ON CONFLICT DO NOTHING;

    -- 3. Trending Products (global)
    INSERT INTO public.user_recommendations (user_id, product_id, score, reason, expires_at)
    SELECT p_user_id, p.id, 5, 'Trending Now', now() + interval '24 hours'
    FROM public.products p
    WHERE p.deleted_at IS NULL
    ORDER BY p.total_sales DESC, p.rating_avg DESC
    LIMIT 5
    ON CONFLICT DO NOTHING;
END;
$$ LANGUAGE plpgsql;



